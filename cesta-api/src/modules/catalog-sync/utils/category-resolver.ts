function normalize(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '');
}

const WORD_BOUNDARY = /[^a-z0-9]/;

/**
 * Prefix-boundary match: keyword precedido por boundary (início ou
 * non-alphanum). Sufixo livre — cobre plurais ("panal" ⊂ "panales"),
 * flexões ("carniceri" ⊂ "carniceria"). Evita "te" matchar "entero"
 * (char antes = "n", alphanum → fail).
 */
function matchKeyword(haystack: string, needle: string): boolean {
  if (!needle) return false;
  let searchFrom = 0;
  while (searchFrom <= haystack.length - needle.length) {
    const idx = haystack.indexOf(needle, searchFrom);
    if (idx < 0) return false;
    const before = idx === 0 ? ' ' : haystack[idx - 1];
    if (WORD_BOUNDARY.test(before)) return true;
    searchFrom = idx + 1;
  }
  return false;
}

/**
 * Ordem de avaliação: slugs mais específicos primeiro pra evitar
 * false positives dos slugs genéricos. Ex: "Fairy lavavajillas limón"
 * → limpieza antes de frutas-verduras; "Colgate pasta de dientes" →
 * higiene antes de despensa ("pasta").
 */
const PRIORITY_ORDER: CategorySlug[] = [
  'bebes',
  'mascotas',
  'higiene',
  'limpieza',
  'congelados',
  'snacks-dulces',
  'bebidas',
  'salsas-conservas',
  'pescado',
  'despensa',
  'lacteos',
  'pan-bolleria',
  'desayuno-cereales',
  'carne',
  'frutas-verduras',
];

const RULES_BY_SLUG: Map<CategorySlug, Rule> = new Map(
  RULES.map((r) => [r.slug, r]),
);

/**
 * Determina slug de categoria baseado em nome + hint (hint tem
 * prioridade quando contém match direto de slug). Retorna null se
 * nenhuma regra bate — caller mantém `categoryId=null`.
 */
export function resolveCategorySlug(
  productName: string,
  hint?: string | null,
): CategorySlug | null {
  const haystack = normalize(`${hint ?? ''} ${productName}`);
  for (const slug of PRIORITY_ORDER) {
    const rule = RULES_BY_SLUG.get(slug);
    if (!rule) continue;
    for (const kw of rule.keywords) {
      const needle = normalize(kw).trim();
      if (needle.length === 0) continue;
      if (matchKeyword(haystack, needle)) return rule.slug;
    }
  }
  return null;
}


